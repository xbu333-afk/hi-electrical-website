/**
 * מקור האמת היחיד לשאלות ותשובות בעמוד /faq.
 *
 * התשובה נשמרת כרצף מקטעים ולא כ-JSX, כדי שאותו מקור יזין גם את הטקסט
 * הנראה בעמוד וגם את ה-Answer ב-JSON-LD. כך המראה הכפול (DOM + סכימה)
 * מדויק מעצם המבנה, ולא בזכות שכפול ידני שנוטה להתפצל עם הזמן.
 */

/** מקטע טקסט רגיל, מקטע מודגש, או מקטע שמוצג כקישור */
export type FaqSegment =
  | string
  | { text: string; strong: true }
  | {
      text: string;
      href: string;
      /** קישור יוצא — נפתח בלשונית חדשה ומסומן ככזה לקוראי מסך */
      external?: boolean;
    };

export type FaqItem = {
  /** משמש גם כעוגן בכתובת וגם כמזהה ב-JSON-LD */
  id: string;
  question: string;
  answer: readonly FaqSegment[];
};

export type FaqCategory = {
  id: string;
  title: string;
  items: readonly FaqItem[];
};

/** מחלץ את הטקסט הנקי של תשובה — בדיוק מה שהמשתמש רואה בעמוד */
export function faqAnswerText(answer: readonly FaqSegment[]): string {
  return answer.map((part) => (typeof part === "string" ? part : part.text)).join("");
}

